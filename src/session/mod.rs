impl Session {
    /// Publish status without ever co-holding the manager lifecycle lock.
    /// Connected is mirrored before the status value becomes visible; Detached
    /// clears the mirror only after the status value is committed.
    pub fn set_status(&self, status: SessionStatus) {
        let mut current = self.status.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        match status {
            SessionStatus::Connected => {
                self.is_connected.store(true, Ordering::Release);
                *current = SessionStatus::Connected;
            }
            SessionStatus::Detached { since } => {
                *current = SessionStatus::Detached { since };
                self.is_connected.store(false, Ordering::Release);
            }
        }
    }

    #[must_use]
    pub fn is_connected(&self) -> bool {
        self.is_connected.load(Ordering::Acquire)
    }

    /// Revert a failed attach publication after lifecycle membership validation.
    pub fn mark_failed_attach(&self) {
        self.set_status(SessionStatus::Detached { since: std::time::Instant::now() });
        self.mark_exited();
    }

    /// Explicitly kill the child process. Safe to call multiple times (idempotent).
    /// After this, the PTY reader task's `reader.read()` will return Err/Ok(0),
    /// causing it to exit and drop its `Arc<Session>`, which triggers `Drop`.
    pub fn kill_child(&self) {
        self.kill_backend_sync();
    }

    /// Kill the backend and confirm that it terminated without waiting indefinitely.
    ///
    /// Returns `false` when the backend lock is held or termination cannot be
    /// confirmed within the bounded polling window.
    pub fn kill_child_and_confirm(&self) -> bool {
        let Ok(mut backend) = self.backend.try_lock() else {
            return false;
        };

        let confirmed = match &mut *backend {
            SessionBackend::Local { child, .. } => {
                #[cfg(unix)]
                if let Some(pid) = child.process_id() {
                    #[allow(clippy::cast_possible_wrap)]
                    let process_group = pid as i32;
                    unsafe {
                        libc::killpg(process_group, libc::SIGTERM);
                    }
                    std::thread::sleep(std::time::Duration::from_millis(50));
                    unsafe {
                        libc::killpg(process_group, libc::SIGKILL);
                    }
                }
                let _ = child.kill();

                let deadline = std::time::Instant::now() + std::time::Duration::from_millis(250);
                loop {
                    match child.try_wait() {
                        Ok(Some(_)) => break true,
                        Ok(None) if std::time::Instant::now() < deadline => {
                            std::thread::sleep(std::time::Duration::from_millis(10));
                        }
                        Ok(None) | Err(_) => break false,
                    }
                }
            }
            SessionBackend::Ssh => self
                .ssh_cmd_tx
                .lock()
                .unwrap_or_else(std::sync::PoisonError::into_inner)
                .as_ref()
                .is_some_and(|tx| tx.send(SshCmd::Close).is_ok()),
            SessionBackend::Exited => true,
        };

        if confirmed {
            *backend = SessionBackend::Exited;
        }
        confirmed
    }

    /// Confirm a naturally-ended backend before its crash-recovery entry is removed.
    /// Uncertainty is deliberately reported as false so boot recovery retains it.
    pub fn natural_exit_confirmed(&self, pane_id: &str) -> bool {
        let Ok(mut backend) = self.backend.try_lock() else {
            return false;
        };
        match &mut *backend {
            SessionBackend::Local { child, .. } => match child.try_wait() {
                Ok(Some(_)) => ledger::termination_confirmed(pane_id),
                Ok(None) | Err(_) => false,
            },
            SessionBackend::Ssh | SessionBackend::Exited => ledger::termination_confirmed(pane_id),
        }
    }

    /// 同步清理后端（用于 `kill_child` 和 Drop）
    fn kill_backend_sync(&self) {
        let Ok(mut backend) = self.backend.try_lock() else {
            // 锁被持有（SSH async 操作中），跳过同步清理
            // SSH reader task 会在连接关闭时自行清理
            return;
        };
        // Move all backend resources out before waiting for the child. In particular,
        // dropping the PTY master wakes a ConPTY reader that can remain blocked after exit.
        let previous = std::mem::replace(&mut *backend, SessionBackend::Exited);
        match previous {
            SessionBackend::Local { writer, master, mut child } => {
                let pid = child.process_id();
                #[cfg(unix)]
                if let Some(pid) = pid {
                    #[allow(clippy::cast_possible_wrap)]
                    let process_group = pid as i32;
                    unsafe {
                        libc::killpg(process_group, libc::SIGTERM);
                    }
                    std::thread::sleep(std::time::Duration::from_millis(50));
                    unsafe {
                        libc::killpg(process_group, libc::SIGKILL);
                    }
                }
                let _ = child.kill();
                drop(writer);
                drop(master);
                let _ = child.wait();
                self.mark_exited();
                info!("Session child killed: pid={:?}", pid);
            }
            SessionBackend::Ssh => {
                // SSH channel is owned by the reader task; signal it to close
                if let Some(tx) = self
                    .ssh_cmd_tx
                    .lock()
                    .unwrap_or_else(std::sync::PoisonError::into_inner)
                    .as_ref()
                {
                    let _ = tx.send(SshCmd::Close);
                }
                self.mark_exited();
                info!("SSH session marked as exited");
            }
            SessionBackend::Exited => {}
        }
    }

    /// 异步清理 SSH channel
    pub fn kill_backend_async(&self) {
        if let Some(tx) =
            self.ssh_cmd_tx.lock().unwrap_or_else(std::sync::PoisonError::into_inner).as_ref()
        {
            let _ = tx.send(SshCmd::Close);
            self.mark_exited();
            info!("SSH close command sent");
        }
    }

    /// 是否为 SSH 会话
    pub fn is_ssh(&self) -> bool {
        self.ssh_params.is_some()
    }

    /// Check if the child process has exited.
    pub fn is_exited(&self) -> bool {
        *self.exited.lock().unwrap_or_else(std::sync::PoisonError::into_inner)
    }

    /// Mark the session as exited.
    pub fn mark_exited(&self) {
        *self.exited.lock().unwrap_or_else(std::sync::PoisonError::into_inner) = true;
    }

    /// 同步写入输入数据（仅支持 Local backend）
    /// 用于现有的同步调用点，SSH backend 应使用 `write_input_async`
    ///
    /// # Errors
    /// Returns an error if the backend lock is held or the write fails.
    pub fn write_input_sync(&self, data: &[u8]) -> Result<(), String> {
        let Ok(mut backend) = self.backend.try_lock() else {
            return Err("backend lock held".into());
        };
        Self::write_input_locked(&mut backend, data)
    }

    /// Write input while waiting for the backend lock from a blocking thread.
    ///
    /// Callers MUST be inside `tokio::task::spawn_blocking` (or otherwise off-runtime), because
    /// `blocking_lock` panics when called on a Tokio worker thread. Waiting is intentional: a
    /// superseded connection's writer may wait and write its already-dequeued batch slightly late
    /// instead of failing fast.
    ///
    /// # Errors
    /// Returns an error if the backend is not local or the write fails.
    pub fn write_input_blocking(&self, data: &[u8]) -> Result<(), String> {
        let mut backend = self.backend.blocking_lock();
        Self::write_input_locked(&mut backend, data)
    }

    fn write_input_locked(backend: &mut SessionBackend, data: &[u8]) -> Result<(), String> {
        match &mut *backend {
            SessionBackend::Local { writer, .. } => {
                writer.write_all(data).map_err(|e| e.to_string())?;
                writer.flush().map_err(|e| e.to_string())?;
                Ok(())
            }
            SessionBackend::Ssh => Err("use write_input_async for SSH sessions".into()),
            SessionBackend::Exited => Err("session exited".into()),
        }
    }

    /// Resize the PTY and virtual screen from a blocking thread.
    ///
    /// Unlike the old `try_lock` version, this waits for the backend lock
    /// instead of silently skipping the PTY resize while still updating `size`
    /// and the virtual screen. A skipped PTY resize would leave the PTY, the
    /// server screen, and every client's grid disagreeing indefinitely.
    ///
    /// Callers MUST be inside `tokio::task::spawn_blocking` (or otherwise off
    /// the async runtime), because `blocking_lock` panics on a Tokio worker.
    ///
    /// # Errors
    /// Returns an error if the PTY/SSH resize fails. On error, `size` and the
    /// virtual screen are left untouched.
    pub(crate) fn resize_blocking(&self, cols: u16, rows: u16) -> Result<ResizeOutcome, String> {
        if self.is_exited() {
            return Ok(ResizeOutcome::Skipped);
        }
        if self.is_ssh() {
            let tx = self.ssh_cmd_tx.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
            let Some(tx) = tx.as_ref() else {
                return Err("SSH cmd channel closed".into());
            };
            tx.send(SshCmd::Resize(cols, rows))
                .map_err(|_| "SSH cmd channel closed".to_string())?;
        } else {
            let mut backend = self.backend.blocking_lock();
            if let SessionBackend::Local { master, .. } = &mut *backend {
                use portable_pty::PtySize;
                master
                    .resize(PtySize { rows, cols, pixel_width: 0, pixel_height: 0 })
                    .map_err(|e| e.to_string())?;
            }
        }
        // Only publish derived state once the backend accepted the resize.
        *self.size.lock().unwrap_or_else(std::sync::PoisonError::into_inner) = (cols, rows);
        self.screen
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .resize(cols as usize, rows as usize);
        Ok(ResizeOutcome::Applied)
    }

    /// Current PTY-size owner, if any.
    #[must_use]
    pub fn size_owner_id(&self) -> Option<u64> {
        *self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner)
    }

    /// Tell every client except `origin_id` that the PTY size is now (cols, rows).
    fn broadcast_resize_to_peers(&self, origin_id: u64, cols: u16, rows: u16) {
        let mut clients = self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        clients.retain(|client| !client.tx.is_closed());
        for client in clients.iter().filter(|client| client.id != origin_id) {
            if client.tx.try_send(SessionClientEvent::Resize { cols, rows }).is_err() {
                tracing::debug!("broadcast: client channel full, dropping resize {cols}x{rows}");
            }
        }
    }

    /// Explicit ownership claim from user input/focus/tap. The claim always
    /// wins (that is the product rule: the device being used gets its native
    /// size), then the PTY is resized and the old owner is told to follow.
    ///
    /// # Errors
    /// Returns an error if the PTY/SSH resize fails. Ownership is reverted to
    /// the previous client in that case.
    pub async fn claim_and_resize(
        &self,
        client_id: u64,
        cols: u16,
        rows: u16,
    ) -> Result<(), String> {
        if self.is_exited() {
            return Ok(());
        }
        if cols < 2 || rows < 2 {
            return Err("invalid resize dimensions".into());
        }
        // Serialize with debounced resizes and snapshot handshakes so a stale
        // resize cannot overwrite this claim after it was accepted.
        let _resize_gate = self.resize_gate.lock().await;
        let current = *self.size.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        tracing::debug!("claim: client={client_id} requested={cols}x{rows} current={current:?}");
        if current == (cols, rows) {
            // The PTY already has this size. Do not resize. If ownership moved,
            // still tell the peers: a stale owner must drop `_isOwner` and claim
            // again on its next gesture. Repeated claims by the same owner stay
            // silent, so this cannot become a claim/reclaim loop.
            let previous = {
                let mut owner =
                    self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
                owner.replace(client_id)
            };
            if previous != Some(client_id) {
                self.broadcast_resize_to_peers(client_id, cols, rows);
                tracing::debug!(
                    "claim same-size ownership transfer: client={client_id} {cols}x{rows} previous={previous:?}"
                );
            }
            return Ok(());
        }
        let previous = {
            let mut owner =
                self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
            owner.replace(client_id)
        };
        if self.is_sync_active() {
            self.set_sync_mode(false);
        }
        if let Err(e) = self.resize_async(cols, rows).await {
            let mut owner =
                self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
            if *owner == Some(client_id) {
                *owner = previous;
            }
            return Err(e);
        }
        self.broadcast_resize_to_peers(client_id, cols, rows);
        tracing::debug!("claim applied: client={client_id} {cols}x{rows}");
        Ok(())
    }

    /// 异步 resize，支持 SSH channel
    ///
    /// # Errors
    /// Returns an error if the resize operation fails.
    pub async fn resize_async(&self, cols: u16, rows: u16) -> Result<(), String> {
        if self.is_exited() {
            return Ok(());
        }
        // SSH: send resize command to reader task (owns the channel)
        if self.is_ssh() {
            if let Some(tx) =
                self.ssh_cmd_tx.lock().unwrap_or_else(std::sync::PoisonError::into_inner).as_ref()
            {
                let _ = tx.send(SshCmd::Resize(cols, rows));
            }
        } else {
            let mut backend = self.backend.lock().await;
            match &mut *backend {
                SessionBackend::Local { master, .. } => {
                    use portable_pty::PtySize;
                    master
                        .resize(PtySize { rows, cols, pixel_width: 0, pixel_height: 0 })
                        .map_err(|e| e.to_string())?;
                }
                SessionBackend::Ssh | SessionBackend::Exited => {}
            }
        }
        *self.size.lock().unwrap_or_else(std::sync::PoisonError::into_inner) = (cols, rows);
        self.screen
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .resize(cols as usize, rows as usize);
        Ok(())
    }

    /// Fit-then-snapshot handshake (proposal 3): resize PTY + size + screen to
    /// the client's requested (cols, rows), then in one critical section take
    /// the scrollback + snapshot and enqueue `ReplayBegin` + chunks + `ReplayEnd`
    /// directly to the target client's mpsc channel, then clear its
    /// `snapshot_pending` flag so future `broadcast()` Output is delivered
    /// normally (and lands after `ReplayEnd` due to mpsc FIFO).
    ///
    /// Wire order per client: [`ReplayBegin`] -> [scrollback chunks] -> [snapshot]
    /// -> [`ReplayEnd`] -> [post-snapshot live Output]. Frontend diverts the
    /// chunks into its transaction buffer and writes them to xterm as a single
    /// batch on `ReplayEnd`, eliminating the settle-ladder / `ResizeObserver`
    /// mid-write interrupts that caused refresh-misalign (P2).
    ///
    /// Holding the clients lock blocks concurrent `broadcast()` from enqueuing
    /// to this client during the snapshot sequence; holding the screen lock
    /// blocks PTY reader from feeding new bytes during `snapshot()`. Bytes that
    /// were already in `output_rx` when this method started MAY be processed by
    /// broadcast after we release - their effect is in the snapshot, so the
    /// client could double-paint them briefly. Full dedup requires the seq
    /// system (proposal 2); MV accepts the rare glitch.
    ///
    /// # Errors
    /// Returns an error if PTY resize fails or the client has disconnected.
    pub async fn atomic_resize_and_snapshot_for_client(
        &self,
        client_id: u64,
        cols: u16,
        rows: u16,
        claim: bool,
    ) -> Result<(), String> {
        if self.is_exited() {
            let _ = self.recover_snapshot_if_pending(client_id);
            return Ok(());
        }

        // Hold the resize gate through snapshot encoding and replay enqueue so
        // no claim/resize can move the PTY between resize and snapshot.
        let _resize_gate = self.resize_gate.lock().await;
        let previous_owner =
            *self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        // Allowed to resize when the client explicitly claims, when it already
        // owns the PTY, or when nobody owns it yet (first client on a pane).
        let should_resize = claim || previous_owner.is_none() || previous_owner == Some(client_id);
        let ownership_changed = should_resize && previous_owner != Some(client_id);
        let current = *self.size.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        // An identical size needs no PTY work and no peer broadcast; only the
        // ownership transfer matters.
        let needs_resize = should_resize && current != (cols, rows);
        tracing::debug!(
            "snapshot request: client={client_id} requested={cols}x{rows} claim={claim} current={current:?} should_resize={should_resize} needs_resize={needs_resize}"
        );
        let (snap_cols, snap_rows) = if needs_resize {
            {
                let mut owner =
                    self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
                *owner = Some(client_id);
            }
            if self.is_sync_active() {
                self.set_sync_mode(false);
            }
            if let Err(e) = self.resize_async(cols, rows).await {
                tracing::warn!(
                    "atomic resize+snapshot: resize {cols}x{rows} failed, client={client_id}: {e}"
                );
                let mut owner =
                    self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
                if *owner == Some(client_id) {
                    *owner = previous_owner;
                }
                // Liveness over geometry: never leave this client pending forever.
                // Fall back to a replay at the current size.
                let _ = self.recover_snapshot_if_pending(client_id);
                return Err(e);
            }
            (cols, rows)
        } else if should_resize {
            // Same size, but the claim transfers ownership.
            *self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner) =
                Some(client_id);
            (cols, rows)
        } else {
            // Non-owner: replay at the current owner size without touching the PTY.
            current
        };

        let mut clients = self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        clients.retain(|c| !c.tx.is_closed());
        let Some(client) = clients.iter().find(|c| c.id == client_id) else {
            return Err("snapshot target client not found or disconnected".into());
        };
        let tx = client.tx.clone();
        let (scrollback_chunks, snapshot) = self.take_snapshot();

        // Enqueue replay sequence directly to the client's mpsc::Sender.
        // Bypasses send_chunk_to_clients' snapshot_pending check - control
        // events and snapshot chunks must reach the client even while pending.
        let complete =
            Self::enqueue_snapshot_replay(&tx, snap_cols, snap_rows, scrollback_chunks, snapshot);

        // Clear snapshot_pending AFTER ReplayEnd is enqueued. broadcast() that
        // runs after we release the clients lock will see snapshot_pending=false
        // and enqueue post-snapshot Output normally - it lands after ReplayEnd
        // in the mpsc FIFO, preserving wire order.
        if let Some(client) = clients.iter().find(|c| c.id == client_id) {
            client.snapshot_pending.store(false, Ordering::Relaxed);
        }
        if !complete {
            tracing::warn!(
                "atomic resize+snapshot: replay enqueue incomplete for client={client_id} ({snap_cols}x{snap_rows}); pending cleared, live output resumes"
            );
        }
        drop(clients);
        if needs_resize || ownership_changed {
            self.broadcast_resize_to_peers(client_id, snap_cols, snap_rows);
        }

        Ok(())
    }

    /// Snapshot the virtual screen. The caller must hold the clients lock when
    /// this is part of a replay sequence, to prevent a concurrent broadcast from
    /// interleaving with `ReplayBegin`/`ReplayEnd`.
    fn take_snapshot(&self) -> (Vec<String>, String) {
        let screen = self.screen.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        (screen.snapshot_scrollback_chunks(200), screen.snapshot_for_replay())
    }

    /// Enqueue a complete replay transaction. Returns false if any event could
    /// not be queued (channel full/closed); the caller still clears the pending
    /// flag so live output can resume instead of dropping it forever.
    fn enqueue_snapshot_replay(
        tx: &mpsc::Sender<SessionClientEvent>,
        cols: u16,
        rows: u16,
        scrollback_chunks: Vec<String>,
        snapshot: String,
    ) -> bool {
        let mut complete = tx.try_send(SessionClientEvent::ReplayBegin { cols, rows }).is_ok();
        for chunk in scrollback_chunks {
            complete &= tx.try_send(SessionClientEvent::Output(chunk)).is_ok();
        }
        complete &= tx.try_send(SessionClientEvent::Output(snapshot)).is_ok();
        complete &= tx.try_send(SessionClientEvent::ReplayEnd).is_ok();
        complete
    }

    /// Recover a client that is still `snapshot_pending` (its `SnapshotRequest`
    /// never arrived, or failed server-side). Replays at the session's current
    /// size without resizing the PTY, then clears the flag so `broadcast()`
    /// stops dropping live output. Returns true when a recovery was emitted.
    pub fn recover_snapshot_if_pending(&self, client_id: u64) -> bool {
        // Cheap pre-check before touching synchronized output: the watchdog
        // calls this for every attached client, and ending an active DEC 2026
        // block on a client that already completed its handshake cuts a frame
        // mid-draw for no reason. `set_sync_mode(false)` also takes the sync
        // lock, so it must not run while the clients lock is held (broadcast
        // order is sync -> clients); check pending first, then release.
        let pending =
            self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner).iter().any(
                |client| client.id == client_id && client.snapshot_pending.load(Ordering::Relaxed),
            );
        if !pending {
            return false;
        }
        if self.is_sync_active() {
            self.set_sync_mode(false);
        }
        let mut clients = self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        clients.retain(|client| !client.tx.is_closed());
        let Some(client) = clients.iter().find(|client| client.id == client_id) else {
            return false;
        };
        if !client.snapshot_pending.load(Ordering::Relaxed) {
            return false;
        }
        let tx = client.tx.clone();
        let (cols, rows) = *self.size.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        let (scrollback_chunks, snapshot) = self.take_snapshot();
        let complete = Self::enqueue_snapshot_replay(&tx, cols, rows, scrollback_chunks, snapshot);
        if let Some(client) = clients.iter().find(|client| client.id == client_id) {
            client.snapshot_pending.store(false, Ordering::Relaxed);
        }
        if !complete {
            tracing::warn!(
                "snapshot recovery: replay enqueue incomplete for client={client_id} ({cols}x{rows}); pending cleared"
            );
        }
        true
    }

    /// Arm a one-shot watchdog for a freshly attached client. If the client has
    /// not completed the fit-then-snapshot handshake within
    /// [`SNAPSHOT_WATCHDOG_MS`], send a recovery snapshot at the current size
    /// and clear `snapshot_pending` instead of dropping live output forever.
    pub fn spawn_snapshot_watchdog(session: Arc<Self>, client_id: u64, pane_id: String) {
        tokio::spawn(async move {
            tokio::time::sleep(std::time::Duration::from_millis(SNAPSHOT_WATCHDOG_MS)).await;
            if session.recover_snapshot_if_pending(client_id) {
                tracing::warn!(
                    pane = %pane_id,
                    client_id,
                    timeout_ms = SNAPSHOT_WATCHDOG_MS,
                    "snapshot watchdog: client still pending; sent recovery snapshot"
                );
            }
        });
    }

    /// 异步写入输入数据到后端
    ///
    /// # Errors
    /// Returns an error if the write operation fails.
    pub async fn write_input_async(&self, data: &[u8]) -> Result<(), String> {
        // SSH: send input to reader task (owns the channel)
        if self.is_ssh() {
            if let Some(tx) =
                self.ssh_cmd_tx.lock().unwrap_or_else(std::sync::PoisonError::into_inner).as_ref()
            {
                tx.send(SshCmd::Input(data.to_vec()))
                    .map_err(|_| "SSH cmd channel closed".to_string())?;
                return Ok(());
            }
            return Err("SSH session not initialized".into());
        }
        let mut backend = self.backend.lock().await;
        match &mut *backend {
            SessionBackend::Local { writer, .. } => {
                writer.write_all(data).map_err(|e| e.to_string())?;
                writer.flush().map_err(|e| e.to_string())?;
            }
            SessionBackend::Ssh => {}
            SessionBackend::Exited => return Err("session exited".into()),
        }
        Ok(())
    }

    /// Debounced resize: coalesces rapid calls (e.g. window drag) and applies
    /// the latest size after a 25ms quiet period. Ensures the final resize is
    /// always applied even if no further calls arrive.
    pub fn resize_debounced(&self, origin_id: u64, cols: u16, rows: u16) {
        tracing::debug!("resize_debounced: {cols}x{rows}");
        let _ = self.resize_tx.send(Some((origin_id, cols, rows)));
    }

    pub fn apply_and_broadcast_resize(&self, origin_id: u64, cols: u16, rows: u16) {
        // Called from the PTY/SSH debounce task's blocking thread. Serialize
        // with explicit claims and snapshot handshakes so a stale debounced
        // resize cannot overwrite a claim that landed in the meantime.
        let _resize_gate = self.resize_gate.blocking_lock();
        {
            let mut clients =
                self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
            clients.retain(|client| !client.tx.is_closed());
            if !clients.iter().any(|client| client.id == origin_id) {
                return;
            }
        }
        // A non-owner may not change the PTY size. Tell it the owner's size so
        // it can follow instead of drifting.
        let owner = *self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        if let Some(owner_id) = owner {
            if owner_id != origin_id {
                let (current_cols, current_rows) =
                    *self.size.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
                let mut clients =
                    self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
                clients.retain(|client| !client.tx.is_closed());
                if let Some(client) = clients.iter().find(|client| client.id == origin_id) {
                    let _ = client.tx.try_send(SessionClientEvent::Resize {
                        cols: current_cols,
                        rows: current_rows,
                    });
                }
                tracing::debug!(
                    "apply_and_broadcast_resize: rejected non-owner resize {cols}x{rows}, origin={origin_id}, owner={owner_id}"
                );
                return;
            }
        }
        // Identical size: no PTY work and no broadcast. Re-broadcasting the
        // same size makes a peer follow and can trigger a claim/reclaim loop.
        let current = *self.size.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        if current == (cols, rows) {
            if owner.is_none() {
                *self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner) =
                    Some(origin_id);
            }
            tracing::debug!("apply_and_broadcast_resize: no-op {cols}x{rows}, origin={origin_id}");
            return;
        }
        // ghostty pattern (src/terminal/c/terminal.zig:483-485): resize breaks
        // synchronized output mode. The DEC 2026 spec explicitly allows the
        // terminal to end sync mode on resize, and doing so prevents the
        // buffer-stuck bug where a PTY that goes silent mid-sync (e.g. Claude
        // Code waiting on an API response during a window resize) leaves
        // synchronized output active forever and the client sees a frozen screen.
        //
        // We flush BEFORE resizing so clients receive the pre-resize buffered
        // output at the old dimensions, then the resize event, then
        // post-resize output at the new dimensions - coherent ordering.
        if self.is_sync_active() {
            tracing::debug!("apply_and_broadcast_resize: breaking sync mode for resize, pane=?");
            self.set_sync_mode(false);
        }
        match self.resize_blocking(cols, rows) {
            Ok(ResizeOutcome::Applied) => {}
            Ok(ResizeOutcome::Skipped) => {
                tracing::debug!(
                    "apply_and_broadcast_resize: skipped {cols}x{rows} (session exited), origin={origin_id}"
                );
                return;
            }
            Err(e) => {
                tracing::warn!(
                    "apply_and_broadcast_resize: PTY resize {cols}x{rows} failed, origin={origin_id}: {e}"
                );
                return;
            }
        }
        // The first client to resize a fresh pane becomes its size owner.
        if owner.is_none() {
            *self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner) =
                Some(origin_id);
        }
        tracing::debug!("resize applied: origin={origin_id} {cols}x{rows}");
        self.broadcast_resize_to_peers(origin_id, cols, rows);
    }

    pub fn clear_tauri_client_if(&self, id: u64) {
        let mut tauri_client_id =
            self.tauri_client_id.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        if *tauri_client_id == Some(id) {
            *tauri_client_id = None;
        }
    }

    /// Release the Tauri IPC forwarder client, if one is registered, by
    /// dropping its event channel. The PTY and any other clients are left
    /// untouched. Returns true when no clients remain, so the caller can mark
    /// the session detached.
    pub fn release_tauri_client(&self) -> bool {
        let client_id =
            self.tauri_client_id.lock().unwrap_or_else(std::sync::PoisonError::into_inner).take();
        if let Some(client_id) = client_id {
            self.remove_client(client_id);
        }
        !self.has_clients()
    }

    pub fn on_pty_output(&self, data: &[u8]) {
        if matches!(self.shell_launch_kind, crate::platform::shell::ShellLaunchKind::Wsl { .. }) {
            return;
        }
        let default_home = crate::platform::shell::home_dir();
        let remote_home_guard =
            self.remote_home.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        let home = remote_home_guard.as_ref().unwrap_or(&default_home);
        let mut state = self.cwd_state.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        let CwdState { ref mut cwd, ref mut host_cwd, ref mut sniff_buf } = *state;
        cwd::sniff_cwd_from_title_osc(sniff_buf, data, home, cwd, self.ssh_params.is_none());
        if self.ssh_params.is_none() {
            *host_cwd = Some(cwd.clone());
        }
    }

    #[must_use]
    pub fn host_cwd(&self) -> Option<PathBuf> {
        self.cwd_state.lock().unwrap_or_else(std::sync::PoisonError::into_inner).host_cwd.clone()
    }

    #[must_use]
    pub fn cwd_for_workspace(&self) -> Option<PathBuf> {
        let state = self.cwd_state.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        if self.ssh_params.is_some() {
            Some(state.cwd.clone())
        } else {
            state.host_cwd.clone()
        }
    }

    /// Replace the input channel, closing the old one (if any) so the previous
    /// PTY write task exits. Returns the new receiver for the caller to spawn
    /// a write task on.
    pub fn replace_input_channel(&self) -> mpsc::UnboundedReceiver<String> {
        let (tx, rx) = mpsc::unbounded_channel();
        let old =
            self.input_tx.lock().unwrap_or_else(std::sync::PoisonError::into_inner).replace(tx);
        drop(old); // close old sender -> old write task's recv() returns None
        rx
    }

    pub fn add_client(&self) -> (u64, mpsc::Receiver<SessionClientEvent>) {
        // Bounded channel with non-blocking try_send: messages are dropped when
        // full rather than blocking the PTY reader. Keeps the shell responsive.
        let (tx, rx) = mpsc::channel(10240);
        let id = self.next_client_id.fetch_add(1, Ordering::Relaxed);
        self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner).push(
            ClientEndpoint { id, tx, snapshot_pending: std::sync::atomic::AtomicBool::new(true) },
        );
        (id, rx)
    }

    pub fn remove_client(&self, id: u64) {
        self.clients
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
            .retain(|client| client.id != id);
        // The device that owned the PTY size is gone; the next claim wins.
        let mut owner = self.size_owner.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        if *owner == Some(id) {
            *owner = None;
        }
    }

    /// Send a chunk to all clients via non-blocking `try_send`.
    /// Channel-full messages are dropped (not the client) to keep the PTY reader
    /// non-blocking. Closed channels are pruned. Clients with `snapshot_pending`
    /// = true are skipped - their Output is captured by the upcoming snapshot
    /// and sending it live would double-paint.
    fn send_chunk_to_clients(clients: &mut Vec<ClientEndpoint>, chunk: &str) {
        clients.retain(|client| !client.tx.is_closed());
        for client in clients.iter() {
            if client.snapshot_pending.load(Ordering::Relaxed) {
                continue;
            }
            if client.tx.try_send(SessionClientEvent::Output(chunk.to_string())).is_err() {
                tracing::debug!(
                    "broadcast: client channel full, dropping chunk ({}B)",
                    chunk.len()
                );
            }
        }
    }

    pub fn broadcast(&self, msg: &str) {
        if self.is_exited() {
            return;
        }
        let mut sync = self.sync.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        if sync.active {
            let len = msg.len();
            sync.buffer.push(msg.to_string());
            sync.bytes += len;
            if sync.bytes < SYNC_BUFFER_LIMIT {
                return;
            }
            self.flush_sync_buffer_locked(&mut sync);
            return;
        }
        let mut clients = self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        Self::send_chunk_to_clients(&mut clients, msg);
    }

    pub fn is_sync_active(&self) -> bool {
        self.sync.lock().unwrap_or_else(std::sync::PoisonError::into_inner).active
    }

    /// Enable or disable synchronized output mode (DEC mode 2026).
    /// When enabling: mark the sync state active, then enqueue `SyncBegin` while
    /// holding the sync guard, so no subsequent Output can overtake it.
    /// When disabling: mark inactive, flush buffered Output, and enqueue
    /// `SyncEnd` while holding the same guard. A concurrent `broadcast()` then
    /// lands after `SyncEnd` in each client's mpsc channel.
    ///
    /// Both transitions are idempotent: DEC 2026 is a mode (set/reset), not a
    /// nesting counter, so a repeated set is a no-op. This matters because the
    /// client-side transaction depth is driven purely by the events we enqueue
    /// here - emitting `SyncBegin` twice for one logical sync (a program that
    /// nests `CSI ?2026h`, or a single `CSI ?2026;2026h` whose params both hit
    /// the performer's `for &p in &ps` loop) would leave the frontend one
    /// unmatched decrement short and wedge the pane against every later write.
    pub fn set_sync_mode(&self, active: bool) {
        let mut sync = self.sync.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        if active {
            if sync.active {
                return;
            }
            sync.active = true;
            self.enqueue_control(&SessionClientEvent::SyncBegin);
        } else {
            if !sync.active {
                return;
            }
            sync.active = false;
            self.flush_sync_buffer_locked(&mut sync);
            #[cfg(test)]
            if let Some(hook) = self
                .sync_disable_hook
                .lock()
                .unwrap_or_else(std::sync::PoisonError::into_inner)
                .take()
            {
                hook();
            }
            self.enqueue_control(&SessionClientEvent::SyncEnd);
        }
    }

    /// Enqueue a control event (SyncBegin/SyncEnd) to all connected clients.
    /// Channel-full events are dropped (not the client), matching
    /// `send_chunk_to_clients`' policy. Closed channels are pruned.
    fn enqueue_control(&self, event: &SessionClientEvent) {
        let mut clients = self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        clients.retain(|client| !client.tx.is_closed());
        for client in clients.iter() {
            if client.tx.try_send(event.clone()).is_err() {
                tracing::debug!("broadcast: client channel full, dropping control event");
            }
        }
    }

    /// Flush buffered output accumulated during synchronized output mode.
    /// Breaks large payloads into chunks at UTF-8 character boundaries to avoid
    /// freezing the frontend UI thread.
    pub fn flush_sync_buffer(&self) {
        let mut sync = self.sync.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        self.flush_sync_buffer_locked(&mut sync);
    }

    fn flush_sync_buffer_locked(&self, sync: &mut SyncState) {
        let data = std::mem::take(&mut sync.buffer);
        sync.bytes = 0;
        if data.is_empty() {
            return;
        }
        let combined = data.join("");
        let mut clients = self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        let mut start = 0;
        while start < combined.len() {
            let mut end = (start + FLUSH_CHUNK_SIZE).min(combined.len());
            while end > start && !combined.is_char_boundary(end) {
                end -= 1;
            }
            Self::send_chunk_to_clients(&mut clients, &combined[start..end]);
            start = end;
        }
    }

    /// Mark the session exited and notify all connected clients.
    ///
    /// The exited transition is notification/backend state only. It is not a
    /// cleanup winner claim; `SessionManager::close_session` owns that claim.
    pub fn notify_exit_and_mark_exited(&self, pane_id: &str, exit_code: Option<i32>) -> bool {
        let newly_exited = {
            let mut exited = self.exited.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
            let newly_exited = !*exited;
            *exited = true;
            newly_exited
        };
        let mut clients = self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        clients.retain(|client| !client.tx.is_closed());
        for client in clients.iter() {
            if client
                .tx
                .try_send(SessionClientEvent::SessionExit {
                    pane_id: pane_id.to_string(),
                    exit_code,
                })
                .is_err()
            {
                tracing::debug!("broadcast: client channel full, dropping session_exit");
            }
        }
        newly_exited
    }

    pub fn has_clients(&self) -> bool {
        let mut clients = self.clients.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
        clients.retain(|client| !client.tx.is_closed());
        !clients.is_empty()
    }
}

impl Drop for Session {
    fn drop(&mut self) {
        self.kill_backend_sync();
    }
}

